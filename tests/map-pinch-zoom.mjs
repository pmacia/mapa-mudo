import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
try {
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'reduce'});
  page.setDefaultTimeout(5000);
  await page.goto(process.env.BASE_URL||'http://localhost:3002');
  const map=page.locator('[data-map-canvas]');
  const cdp=await page.context().newCDPSession(page);
  const touch=async(type,points)=>{
    await cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([x,y,id],index)=>({x,y,id:id??index}))});
    await page.waitForTimeout(30);
  };
  const view=()=>map.getAttribute('viewBox').then(s=>s.split(/\s+/).map(Number));
  const worldAt=(x,y)=>map.evaluate((svg,[x,y])=>{
    const p=new DOMPoint(x,y).matrixTransform(svg.getScreenCTM().inverse());return {x:p.x,y:p.y};
  },[x,y]);
  const show=async()=>{const button=page.getByRole('button',{name:'Mostrar interfaz',exact:true});if(await button.isVisible())await button.click();};
  const hide=()=>page.getByRole('button',{name:'Ocultar interfaz',exact:true}).click();
  await hide();
  const initial=await view();
  const anchor=await worldAt(130,380);
  await touch('touchStart',[[80,330],[180,430]]);
  await touch('touchMove',[[50,300],[210,460]]);
  const enlarged=await view();
  assert.ok(Math.abs(initial[2]/enlarged[2]-1.6)<0.03,'Spreading two fingers must zoom the map proportionally');
  const anchored=await worldAt(130,380);
  assert.ok(Math.hypot(anchor.x-anchored.x,anchor.y-anchored.y)<1,'The map point between the fingers stays anchored');
  assert.equal(await page.evaluate(()=>visualViewport.scale),1,'Pinching zooms the map rather than the browser page');
  await touch('touchMove',[[80,330],[180,430]]);
  assert.ok(Math.abs((await view())[2]-initial[2])<1,'Bringing fingers together must zoom back out');
  await touch('touchMove',[[110,350],[210,450]]);
  const translated=await worldAt(160,400);
  assert.ok(Math.hypot(anchor.x-translated.x,anchor.y-translated.y)<1,'Moving both fingers pans around the same geographic anchor');
  await touch('touchMove',[[129,379],[131,381]]);
  assert.ok(Math.abs((await view())[2]-initial[2]*2)<1,'Pinch respects the minimum zoom');
  await touch('touchMove',[[5,255],[355,605]]);
  assert.ok(Math.abs((await view())[2]-initial[2]/3)<1,'Pinch respects the maximum zoom');
  await touch('touchMove',[[80,330],[180,430]]);
  await touch('touchEnd',[]);
  // Pan with the remaining finger after a pinch: rebase without a jump.
  await touch('touchStart',[[80,330],[180,430]]);
  await touch('touchMove',[[50,300],[210,460]]);
  await touch('touchEnd',[[210,460,1]]);
  const beforePan=await view();
  await touch('touchMove',[[75,325]]);
  const afterPan=await view();
  assert.equal(afterPan[2],beforePan[2],'Continuing with one finger preserves zoom');
  assert.ok(afterPan[0]<beforePan[0]&&afterPan[1]<beforePan[1],'Remaining finger continues panning');
  await touch('touchCancel',[]);
  await show();await page.getByRole('button',{name:'Recentrar mapa',exact:true}).click();
  // Normal taps and buttons still work after a gesture or cancellation.
  await page.getByRole('button',{name:'Acercar mapa',exact:true}).tap();
  assert.ok((await view())[2]<initial[2]);
  await page.getByRole('button',{name:'Recentrar mapa',exact:true}).tap();
  assert.ok(Math.abs((await view())[2]-initial[2])<1);
  await page.getByRole('button',{name:'Modo Ubicar en el mapa',exact:true}).click();
  const attempts=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('geoespana_player_stats_v2')).totalAttempts);
  const initialAttempts=await attempts();
  await hide();await touch('touchStart',[[80,330],[180,430]]);await touch('touchMove',[[50,300],[210,460]]);await touch('touchEnd',[]);
  // Some browsers can emit a compatibility click after contacts end. It must not answer.
  await map.locator('g.cursor-pointer').first().dispatchEvent('click');
  assert.equal(await attempts(),initialAttempts,'A compatibility click after pinching cannot answer a map question');
  await show();
  await page.getByRole('button',{name:'60 segundos contrarreloj',exact:true}).click();
  const answers=()=>page.locator('.timed-stats [title="Aciertos"],.timed-stats [title="Fallos"]').allInnerTexts().then(items=>items.map(t=>Number(t.match(/\d+/)?.[0])).reduce((a,b)=>a+b,0));
  const beforeAnswers=await answers();
  await hide();await touch('touchStart',[[80,330],[180,430]]);await touch('touchMove',[[50,300],[210,460]]);await touch('touchEnd',[]);await show();
  assert.equal(await answers(),beforeAnswers,'Pinching cannot submit a timed response');
  await page.getByRole('button',{name:'SÍ, ES',exact:true}).tap();
  assert.equal(await answers(),beforeAnswers+1,'Touch answers remain usable after pinching');
  await page.setViewportSize({width:844,height:390});await page.waitForTimeout(100);
  await hide();
  const landscape=await view();
  await touch('touchStart',[[350,150],[450,250]]);await touch('touchMove',[[300,100],[500,300]]);await touch('touchEnd',[]);
  assert.ok((await view())[2]<landscape[2],'Pinch works in mobile landscape');
  await show();
  await page.setViewportSize({width:1200,height:900});
  await page.getByRole('button',{name:'Mapa Mudo Exploratorio',exact:true}).click();
  await page.getByRole('button',{name:'Activar modo edición vectorial',exact:true}).click();
  await page.keyboard.press('Control+n');
  await hide();
  const midpoint=map.locator('#vector-editor-overlay g.cursor-pointer');
  const verticesBefore=await midpoint.count();assert.ok(verticesBefore>=3);
  await touch('touchStart',[[80,200],[180,300]]);await touch('touchMove',[[60,180],[200,320]]);await touch('touchEnd',[]);
  const editorZoom=await view();
  await midpoint.first().tap();
  assert.equal(await midpoint.count(),verticesBefore+1,'Editor midpoint insertion must still work after a map pinch');
  assert.deepEqual(await view(),editorZoom,'Editing a vertex must not pan or zoom the background');
  console.log('PASS touch pinch: proportional zoom, anchor, browser scale, one-finger continuation, cancellation, controls, editor vertices and timed gameplay in portrait/landscape');
}finally{await browser.close();}
